def is_non_legislation_bank(bank: str | None) -> bool:
    """Лежит ли документ в банке, где законодательства нет вовсе (практика/разъяснения)."""
    return bool(bank) and str(bank) in NON_LEGISLATION_BANKS


def foreign_region(bank: str | None, title_head: str, project_region: str) -> str:
    "Субъект акта, если он ТОЧНО не совпадает с субъектом проекта; иначе пусто."
    home = bank_for_region(project_region)
    if not home:
        return ""  # субъект проекта неизвестен — сравнивать не с чем
    named = region_from_text(title_head, head_chars=200)  # сначала заголовок: он точнее банка
    if named and (other := bank_for_region(named)) and other != home:
        return named
    if bank and str(bank) in REGION_BANKS and str(bank) != home:
        return REGION_BANKS[str(bank)][0]
    return ""
