#: Прилагательные окончания названий субъектов («Ульяновск-ой» → «ульяновск»).
_ADJ_ENDINGS = ("ского", "ская", "ской", "ский", "ское", "ские", "ских", "ским", "скую", "скою")


_CASE_ENDINGS = ("ого", "ая", "ой", "ий", "ое", "ые", "ых", "им", "ую", "ью", "а", "ы", "и", "е", "я", "ю", "й", "ь")
_MIN_STEM = int(settings["agents.legal.region_banks.min_stem"])


def _stem(word: str) -> str:
    "Основа слова: срезаем прилагательное/падежное окончание. Обе стороны сравнения"
    w = word
    for end in _ADJ_ENDINGS:
        if w.endswith(end) and len(w) - len(end) >= _MIN_STEM:
            return w[: -len(end)]
    for end in _CASE_ENDINGS:
        if w.endswith(end) and len(w) - len(end) >= _MIN_STEM:
            return w[: -len(end)]
    return w


_GENERIC_STEMS = frozenset(_stem(w) for w in _GENERIC_WORDS)


def region_key(name: str) -> str:
    "Название субъекта в любом падеже → сравнимый ключ («Ульяновской области» →"
    low = (name or "").lower().replace("ё", "е")
    words = [w for w in re.findall(r"[а-я][а-я-]*", low) if w]
    stems = [_stem(w) for w in words]
    return " ".join(s for s in stems if s and s not in _GENERIC_STEMS)


#: Ключ субъекта → банк. Собирается на импорте (таблица статична).
_BANK_BY_KEY: dict[str, str] = {}
for _bank, _aliases in REGION_BANKS.items():
    for _alias in _aliases:
        _key = region_key(_alias)
        if _key:
            _BANK_BY_KEY.setdefault(_key, _bank)


def bank_for_region(name: str | None) -> str | None:
    "Название субъекта → код банка К+ («Ульяновской области» → ``RLAW076``)."
    if not name:
        return None
    return _BANK_BY_KEY.get(region_key(name))


def known_banks() -> frozenset[str]:
    "Все банки таблицы + федеральный — для валидации имени перед запросом."
    return frozenset({FEDERAL_BANK, *REGION_BANKS})


_REGION_HEAD_RE = re.compile(r"([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?)\s+(области|обл\.|края|автономного округа)", re.UNICODE)
_REGION_CAPS_RE = re.compile(r"([А-ЯЁ]{4,}(?:-[А-ЯЁ]{4,})?)\s+(ОБЛАСТИ|КРАЯ|АВТОНОМНОГО ОКРУГА)")

_REPUBLIC_RE = re.compile(r"Республик[аиеу]\s+([А-ЯЁ][А-Яа-яЁё()\s-]{2,30}?)(?=[,.\n]|\s+от\s)", re.UNICODE)


def region_from_text(text: str, *, head_chars: int = 2000) -> str:
    "Субъект РФ из шапки документа («Ульяновской области»); пусто — если не распознан."
    head = (text or "")[:head_chars]
    m = _REGION_HEAD_RE.search(head)
    if m:
        return f"{m.group(1)} {m.group(2)}"
    m = _REGION_CAPS_RE.search(head)
    if m:
        return f"{m.group(1).capitalize()} {m.group(2).lower()}"
    m = _REPUBLIC_RE.search(head)
    if m and bank_for_region(f"Республика {m.group(1)}"):
        return f"Республика {m.group(1).strip()}"
    return ""


