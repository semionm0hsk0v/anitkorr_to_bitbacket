from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from src.agents.enums.common.review import CheckStatus, RiskKind

#: Reserved source ID of the reviewed project. External sources never get it.
PROJECT_SOURCE_ID = "project"


class Citation(BaseModel):
    model_config = ConfigDict(extra="forbid")

    source: str = Field(description="ID прочитанного источника; project — сам проект")
    location: str = Field(default="", description="Пункт, страница или строка таблицы; реквизиты и пункт внешнего акта")
    quote: str = Field(min_length=1, description="Дословный фрагмент указанного источника")


class Risk(BaseModel):
    model_config = ConfigDict(extra="forbid")

    kind: RiskKind
    explanation: str = Field(min_length=1, description="Суть нарушения, применимость нормы и юридическое последствие")
    recommendation: str = Field(min_length=1, description="Как устранить нарушение")

    citations: list[Citation] = Field(
        description=(
            "Первой — цитата проекта (source=project), указывающая основное место нарушения; "
            "затем вторая норма проекта или прочитанные внешние нормы"
        ),
    )


class Check(BaseModel):
    model_config = ConfigDict(extra="forbid")

    kind: RiskKind
    status: CheckStatus
    reason: str = Field(default="", description="Пусто для completed, иначе конкретная причина")


class Review(BaseModel):
    model_config = ConfigDict(extra="forbid")

    findings: list[Risk]
    checks: list[Check] = Field(description="Статус каждого порученного направления")


class LegalSource(BaseModel):
    """Read source retained by the application, never generated by the model."""

    id: str
    text: str
    reference: str = ""
    #: Available edition data as returned by the provider; unknown values are not invented.
    edition: dict[str, Any] = Field(default_factory=dict)
